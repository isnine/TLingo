#!/bin/bash
#
# Writes the gitignored ios/ShareCore/Configuration/AppSecrets.swift.
#
# - Xcode Cloud: require the cloud credentials and fail instead of shipping an app that points at placeholder hosts.
# - TLINGO_CLOUD_SECRET set: write real values from TLINGO_* environment variables.
# - Legacy AITRANSLATOR_* names remain supported while the Xcode Cloud
#   workflows migrate to TLINGO_* names.
# - File already exists: keep it (local developer copy).
# - Otherwise: write placeholders so the app compiles with cloud features disabled.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUTPUT="$ROOT/ios/ShareCore/Configuration/AppSecrets.swift"

trim() {
    local value="$1"
    value="${value#"${value%%[![:space:]]*}"}"
    value="${value%"${value##*[![:space:]]}"}"
    printf '%s' "$value"
}

CLOUD_ENDPOINT="$(trim "${TLINGO_CLOUD_ENDPOINT:-${AITRANSLATOR_CLOUD_ENDPOINT:-}}")"
CLOUD_SECRET="$(trim "${TLINGO_CLOUD_SECRET:-${AITRANSLATOR_CLOUD_SECRET:-}}")"
CLOUD_API_VERSION="$(trim "${TLINGO_CLOUD_API_VERSION:-2025-01-01-preview}")"
: "${CLOUD_API_VERSION:=2025-01-01-preview}"

if [[ -n "${CI_XCODE_CLOUD:-}" ]]; then
    missing_variables=()
    [[ -n "$CLOUD_ENDPOINT" ]] || missing_variables+=("TLINGO_CLOUD_ENDPOINT")
    [[ -n "$CLOUD_SECRET" ]] || missing_variables+=("TLINGO_CLOUD_SECRET")

    if (( ${#missing_variables[@]} > 0 )); then
        printf 'Missing required Xcode Cloud environment variables: %s\n' \
            "${missing_variables[*]}" >&2
        echo "Configure them in the Xcode Cloud workflow before archiving TLingo." >&2
        exit 1
    fi
fi

if [[ -z "$CLOUD_SECRET" && -f "$OUTPUT" ]]; then
    echo "AppSecrets.swift exists; keeping local copy"
    exit 0
fi

EFFECTIVE_ENDPOINT="${CLOUD_ENDPOINT:-https://example.invalid}"
if [[ ! "$EFFECTIVE_ENDPOINT" =~ ^https://[^[:space:]\"#]+$ ]]; then
    echo "Invalid TLINGO_CLOUD_ENDPOINT URL: expected https:// URL without whitespace or '#': $EFFECTIVE_ENDPOINT" >&2
    exit 1
fi

for secret_var in "$CLOUD_SECRET" "$CLOUD_API_VERSION"; do
    if [[ "$secret_var" == *'"#'* ]] || [[ "$secret_var" == *$'\n'* ]] || [[ "$secret_var" == *$'\r'* ]]; then
        echo "Invalid control characters or Swift raw-string delimiter in AppSecrets environment variable" >&2
        exit 1
    fi
done

TMP_OUTPUT="$(mktemp "${OUTPUT}.tmp.XXXXXX")"
trap 'rm -f "$TMP_OUTPUT"' EXIT

cat > "$TMP_OUTPUT" <<EOF
//
//  AppSecrets.swift
//  ShareCore
//
//  Generated by ci_scripts/generate-app-secrets.sh. Do not commit.
//

import Foundation

public enum AppSecrets {
    public static let cloudEndpoint = URL(string: #"$EFFECTIVE_ENDPOINT"#)!
    public static let cloudSecret = #"$CLOUD_SECRET"#
    public static let cloudAPIVersion = #"$CLOUD_API_VERSION"#
}
EOF

if [[ -f "$OUTPUT" ]] && cmp -s "$TMP_OUTPUT" "$OUTPUT"; then
    echo "AppSecrets.swift unchanged; keeping existing file"
    exit 0
fi

mv "$TMP_OUTPUT" "$OUTPUT"
trap - EXIT
echo "Wrote $OUTPUT (cloud configured: $([[ -n "$CLOUD_SECRET" ]] && echo yes || echo no))"
